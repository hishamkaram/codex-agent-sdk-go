// dispatch_oracle_test.go is the behavior-equivalence oracle (golden master)
// guarding the ParseEvent / ParseItem dispatch refactor that replaces the
// hand-written switch statements with lookup tables.
//
// The refactor's failure class is a DROPPED or MIS-KEYED case: a method that
// silently falls through to UnknownEvent, or a method wired to the wrong
// handler. Capturing only the Go type name would miss a mis-binding inside the
// flat-delta family (item/agentMessage/delta, item/plan/delta, … all produce
// *types.ItemUpdated, distinguished only by the inner ItemDelta). So the
// signature for each corpus entry is the concrete Go type name PLUS the
// json.Marshal of the parsed result (or the error string) — a mis-binding
// changes the marshaled bytes even when the outer type matches.
//
// The golden file is regenerated by setting UPDATE_DISPATCH_ORACLE=1. It is
// committed and asserted byte-identical on every run; the dispatch refactor is
// allowed only while this test stays green.

