// signature renders a parsed result + error into a deterministic golden line.
func signature(v any, err error) string {
	if err != nil {
		return fmt.Sprintf("ERR: %s", err.Error())
	}
	b, mErr := json.Marshal(v)
	if mErr != nil {
		return fmt.Sprintf("MARSHAL-ERR: %s", mErr.Error())
	}
	return fmt.Sprintf("%T | %s", v, string(b))
}

func computeDispatchGolden(t *testing.T) map[string]string {
	t.Helper()
	golden := make(map[string]string, len(eventCorpus)+len(itemCorpus))
	for _, e := range eventCorpus {
		ev, err := ParseEvent(jsonrpc.Notification{
			Method: e.method,
			Params: json.RawMessage(e.params),
		})
		golden["event:"+e.method] = signature(ev, err)
	}
	for i, raw := range itemCorpus {
		it, err := ParseItem(json.RawMessage(raw))
		golden[fmt.Sprintf("item:%02d", i)] = signature(it, err)
	}
	return golden
}

// TestDispatchOracle pins ParseEvent and ParseItem dispatch behavior against a
// committed golden file. Regenerate with UPDATE_DISPATCH_ORACLE=1.
func TestDispatchOracle(t *testing.T) {
	t.Parallel()

	goldenPath := filepath.Join("testdata", "dispatch_oracle.golden.json")
	got := computeDispatchGolden(t)

	if os.Getenv("UPDATE_DISPATCH_ORACLE") == "1" {
		// Deterministic, sorted, indented for a reviewable diff.
		keys := make([]string, 0, len(got))
		for k := range got {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		ordered := make([][2]string, 0, len(keys))
		for _, k := range keys {
			ordered = append(ordered, [2]string{k, got[k]})
		}
		buf, err := json.MarshalIndent(ordered, "", "  ")
		if err != nil {
			t.Fatalf("marshal golden: %v", err)
		}
		if err := os.WriteFile(goldenPath, append(buf, '\n'), 0o600); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		t.Logf("updated golden: %s (%d entries)", goldenPath, len(got))
		return
	}

	data, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("read golden (regenerate with UPDATE_DISPATCH_ORACLE=1): %v", err)
	}
	var ordered [][2]string
	if err := json.Unmarshal(data, &ordered); err != nil {
		t.Fatalf("unmarshal golden: %v", err)
	}
	want := make(map[string]string, len(ordered))
	for _, kv := range ordered {
		want[kv[0]] = kv[1]
	}

	// Every golden key must be reproduced byte-identically.
	for k, wantSig := range want {
		gotSig, ok := got[k]
		if !ok {
			t.Errorf("dispatch case %q present in golden but missing from current run", k)
			continue
		}
		if gotSig != wantSig {
			t.Errorf("dispatch drift for %q:\n  want: %s\n  got:  %s", k, wantSig, gotSig)
		}
	}
	// No new/unexpected keys (corpus stayed in sync).
	for k := range got {
		if _, ok := want[k]; !ok {
			t.Errorf("dispatch case %q present in current run but missing from golden", k)
		}
	}
}
